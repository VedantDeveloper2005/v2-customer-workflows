"""Deterministic, create-only Linux App Service plan. No customer code or secrets.

Shared by the API and trusted customer runner. Every generated byte is bound to
the request; approval/execution are deliberately absent from this milestone.
"""
import hashlib
import json
import copy

ENGINE_VERSION = "1.13.2"
PROVIDER_VERSION = "4.81.0"
POLICY_VERSION = "app-service-golden.v3"


def encode(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False).encode()


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def app_resource_id(manifest):
    return f"/subscriptions/{manifest['subscription_id']}/resourceGroups/{manifest['resource_group']}/providers/Microsoft.Web/sites/{manifest['input']['app_name']}"


def resource_ids(manifest):
    scope = f"/subscriptions/{manifest['subscription_id']}/resourceGroups/{manifest['resource_group']}"
    p = manifest["input"]
    return {"scope": scope, "app": app_resource_id(manifest),
        "service_plan": scope + "/providers/Microsoft.Web/serverFarms/" + p["service_plan_name"],
        "identity": scope + "/providers/Microsoft.ManagedIdentity/userAssignedIdentities/" + p["runtime_identity_name"],
        "registry": scope + "/providers/Microsoft.ContainerRegistry/registries/" + p["registry_name"],
        "storage": scope + "/providers/Microsoft.Storage/storageAccounts/" + p["storage_account"]}


def bundle(manifest, lock_bytes):
    p, ids = manifest["input"], resource_ids(manifest)
    image = f"{p['image_repository']}@sha256:{p['image_sha256']}"
    registry = p["registry_name"] + ".azurecr.io"
    app_settings = {"WEBSITES_PORT": str(p["container_port"]), "WEBSITES_ENABLE_APP_SERVICE_STORAGE": "false", "V2_IMAGE_SHA256": p["image_sha256"]}
    site_config = {"linuxFxVersion": f"DOCKER|{registry}/{image}", "acrUseManagedIdentityCreds": True,
        "acrUserManagedIdentityID": p["runtime_client_id"], "alwaysOn": True,
        "minTlsVersion": "1.2", "ftpsState": "Disabled", "http20Enabled": True,
        "appSettings": [{"name": k, "value": v} for k, v in sorted(app_settings.items())]}
    template = {"$schema": "https://schema.management.azure.com/schemas/2019-04-01/deploymentTemplate.json#",
        "contentVersion": "1.0.0.0", "resources": [{"type": "Microsoft.Web/sites", "apiVersion": "2023-12-01",
            "name": p["app_name"], "location": p["location"], "kind": "app,linux,container",
            "identity": {"type": "UserAssigned", "userAssignedIdentities": {ids["identity"]: {}}},
            "properties": {"serverFarmId": ids["service_plan"], "reserved": True, "httpsOnly": True,
                "clientAffinityEnabled": False, "siteConfig": site_config}}]}
    tofu = {"terraform": {"required_version": "= " + ENGINE_VERSION,
        "required_providers": {"azurerm": {"source": "hashicorp/azurerm", "version": "= " + PROVIDER_VERSION}},
        "backend": {"azurerm": {"resource_group_name": manifest["resource_group"], "storage_account_name": p["storage_account"],
            "container_name": p["state_container"], "key": f"v2/{manifest['workspace_id']}/{manifest['project_id']}/{p['app_name']}.tfstate",
            "use_oidc": True, "use_azuread_auth": True, "tenant_id": manifest["azure_tenant_id"],
            "subscription_id": manifest["subscription_id"], "client_id": p["planning_client_id"]}}},
        "provider": {"azurerm": {"features": {}, "subscription_id": manifest["subscription_id"],
            "tenant_id": manifest["azure_tenant_id"], "client_id": p["planning_client_id"], "use_oidc": True,
            "resource_provider_registrations": "none"}},
        "resource": {"azurerm_linux_web_app": {"app": {"name": p["app_name"], "location": p["location"],
            "resource_group_name": manifest["resource_group"], "service_plan_id": ids["service_plan"],
            "https_only": True, "client_affinity_enabled": False, "app_settings": app_settings,
            "identity": {"type": "UserAssigned", "identity_ids": [ids["identity"]]},
            "site_config": {"always_on": True, "minimum_tls_version": "1.2", "ftps_state": "Disabled", "http2_enabled": True,
                "container_registry_use_managed_identity": True, "container_registry_managed_identity_client_id": p["runtime_client_id"],
                "application_stack": {"docker_image_name": image, "docker_registry_url": "https://" + registry}}}}}}
    files = {"main.tf.json": encode(tofu), "what-if.json": encode(template), ".terraform.lock.hcl": lock_bytes}
    # Portable JSON envelope; exact file bytes encoded as UTF-8, no tar metadata.
    return encode({"schema_version": "v2.golden-plan-bundle.v1", "files": {name: raw.decode() for name, raw in files.items()}})


def execution_digest(request_sha, bundle_sha, artifacts):
    return sha(encode({"schema_version": "v2.execution-request.v1", "request_sha256": request_sha,
        "bundle_sha256": bundle_sha, "artifacts": artifacts}))


def summarize(what_if, tofu, manifest):
    """Reject destructive, unknown, extra-resource and mismatched plans locally."""
    if manifest.get("mode") == "app-service-update-plan": return summarize_update(what_if, tofu, manifest)
    ids, p = resource_ids(manifest), manifest["input"]
    changes = what_if.get("changes")
    if what_if.get("status") != "Succeeded" or not isinstance(changes, list) or not 1 <= len(changes) <= 1000:
        raise ValueError("PLAN_REJECTED")
    mutations, seen = [], set()
    for entry in changes:
        resource_id = entry.get("resourceId", "").casefold()
        if resource_id in seen or not resource_id.startswith(ids["scope"].casefold() + "/providers/"):
            raise ValueError("PLAN_REJECTED")
        seen.add(resource_id)
        if entry.get("changeType") == "Ignore" and resource_id != ids["app"].casefold():
            continue  # Existing resources outside this single-resource template.
        mutations.append(entry)
    if len(mutations) != 1: raise ValueError("PLAN_REJECTED")
    change = mutations[0]
    if change.get("resourceId", "").casefold() != ids["app"].casefold() or change.get("changeType") != "Create":
        raise ValueError("PLAN_REJECTED")
    after = change.get("after", {})
    expected = json.loads(json.loads(bundle(manifest, b"{}"))["files"]["what-if.json"])["resources"][0]
    if after.get("type", "").casefold() != "microsoft.web/sites" or after.get("name") != p["app_name"] or after.get("properties", {}).get("siteConfig", {}).get("linuxFxVersion") != expected["properties"]["siteConfig"]["linuxFxVersion"]:
        raise ValueError("PLAN_REJECTED")
    resources = tofu.get("resource_changes")
    if tofu.get("terraform_version") != ENGINE_VERSION or not isinstance(resources, list) or len(resources) != 1 or tofu.get("errored") is True or tofu.get("complete") is False or tofu.get("resource_drift") or tofu.get("deferred_changes"):
        raise ValueError("PLAN_REJECTED")
    resource = resources[0]; delta = resource.get("change", {}); values = delta.get("after", {})
    config = json.loads(json.loads(bundle(manifest, b"{}"))["files"]["main.tf.json"])["resource"]["azurerm_linux_web_app"]["app"]
    if resource.get("address") != "azurerm_linux_web_app.app" or resource.get("mode") != "managed" or resource.get("type") != "azurerm_linux_web_app" or delta.get("actions") != ["create"] or delta.get("before") is not None:
        raise ValueError("PLAN_REJECTED")
    validate_after(values, manifest)
    return {"create_count": 1}


def validate_after(values, manifest):
    ids, p = resource_ids(manifest), manifest["input"]
    config = json.loads(json.loads(bundle(manifest, b"{}"))["files"]["main.tf.json"])["resource"]["azurerm_linux_web_app"]["app"]
    for key in ("name", "location", "resource_group_name", "service_plan_id", "https_only", "client_affinity_enabled", "app_settings"):
        if values.get(key) != config[key]: raise ValueError("PLAN_REJECTED")
    identity, site = values.get("identity"), values.get("site_config")
    if not isinstance(identity, list) or len(identity) != 1 or identity[0].get("type") != "UserAssigned" or identity[0].get("identity_ids") != [ids["identity"]] or not isinstance(site, list) or len(site) != 1:
        raise ValueError("PLAN_REJECTED")
    for key, value in config["site_config"].items():
        actual = site[0].get(key)
        if key == "application_stack":
            if not isinstance(actual, list) or len(actual) != 1 or any(actual[0].get(k) != v for k, v in value.items()): raise ValueError("PLAN_REJECTED")
        elif actual != value: raise ValueError("PLAN_REJECTED")


def has_unknown(value):
    if isinstance(value, dict): return any(has_unknown(v) for v in value.values())
    if isinstance(value, list): return any(has_unknown(v) for v in value)
    return bool(value)


def summarize_update(what_if, tofu, manifest):
    """Only an existing golden state with an exact image-only diff qualifies."""
    ids, p = resource_ids(manifest), manifest["input"]
    try:
        baseline = manifest["baseline"]["attestation"]["payload"]
        previous = baseline["image_sha256"]
        if baseline["kind"] != "known-good-release" or baseline["tenant_id"] != manifest["workspace_id"] or baseline["project_id"] != manifest["project_id"] or baseline["resource_id"].casefold() != ids["app"].casefold() or baseline["registry_name"] != p["registry_name"] or baseline["image_repository"] != p["image_repository"] or baseline["policy_sha256"] != manifest["release_policy"]["sha256"] or previous == p["image_sha256"]: raise ValueError()
        before_manifest = {**manifest, "input": {**p, "image_sha256": previous}}
        changes = what_if["changes"]
        if what_if["status"] != "Succeeded" or not isinstance(changes, list) or not 1 <= len(changes) <= 1000: raise ValueError()
        mutations, seen = [], set()
        for change in changes:
            resource = change["resourceId"].casefold()
            if resource in seen or not resource.startswith(ids["scope"].casefold()+"/providers/"): raise ValueError()
            seen.add(resource)
            if change.get("changeType") == "Ignore" and resource != ids["app"].casefold(): continue
            mutations.append(change)
        if len(mutations) != 1 or mutations[0]["resourceId"].casefold() != ids["app"].casefold() or mutations[0]["changeType"] != "Modify": raise ValueError()
        change = mutations[0]
        delta = change["delta"]
        allowed = {"properties.siteConfig.linuxFxVersion", "properties.siteConfig.appSettings"}
        if not isinstance(delta, list) or not delta or any(d.get("path") not in allowed or d.get("propertyChangeType") not in {"Modify", "Array"} for d in delta): raise ValueError()
        def normalized_arm(value, m):
            actual = copy.deepcopy(value)
            expected = json.loads(json.loads(bundle(m, b"{}"))["files"]["what-if.json"])["resources"][0]
            if actual["type"].casefold() != "microsoft.web/sites" or actual["name"] != p["app_name"]: raise ValueError()
            site = actual["properties"]["siteConfig"]
            desired = expected["properties"]["siteConfig"]
            settings = site["appSettings"]
            if not isinstance(settings, list) or len(settings) != 3 or len({s["name"] for s in settings}) != 3 or {s["name"]: s["value"] for s in settings} != {s["name"]: s["value"] for s in desired["appSettings"]} or site["linuxFxVersion"] != desired["linuxFxVersion"]: raise ValueError()
            site["appSettings"] = {s["name"]: s["value"] for s in settings if s["name"] != "V2_IMAGE_SHA256"}
            site.pop("linuxFxVersion")
            return actual
        if normalized_arm(change["before"], before_manifest) != normalized_arm(change["after"], manifest): raise ValueError()
        if tofu["terraform_version"] != ENGINE_VERSION or tofu.get("errored") is True or tofu.get("complete") is False or tofu.get("resource_drift") or tofu.get("deferred_changes"): raise ValueError()
        resources = tofu["resource_changes"]
        if not isinstance(resources, list) or len(resources) != 1: raise ValueError()
        resource = resources[0]; diff = resource["change"]
        if resource.get("address") != "azurerm_linux_web_app.app" or resource.get("mode") != "managed" or resource.get("type") != "azurerm_linux_web_app" or diff["actions"] != ["update"] or diff.get("importing") or resource.get("importing") or resource.get("previous_address") or resource.get("deposed") or has_unknown(diff.get("after_unknown", {})): raise ValueError()
        validate_after(diff["before"], before_manifest); validate_after(diff["after"], manifest)
        def normalized_tofu(value):
            result = copy.deepcopy(value)
            result["app_settings"].pop("V2_IMAGE_SHA256")
            result["site_config"][0]["application_stack"][0].pop("docker_image_name")
            return result
        if normalized_tofu(diff["before"]) != normalized_tofu(diff["after"]): raise ValueError()
    except (KeyError, TypeError, AttributeError, ValueError): raise ValueError("PLAN_REJECTED") from None
    return {"update_count": 1}
